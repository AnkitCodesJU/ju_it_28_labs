#include <stdio.h>
#include <stdlib.h>
#include <stdbool.h>

#define TOTAL_ADDR 20
#define NUM_FRAMES 3
#define ROWS_PER_PAGE 20
#define OFFSET_BITS 4
#define PAGE_BITS 2

// Helper function to pause and wait for Enter (or quit)
bool wait_for_enter(const char *prompt) {
    char buf[64];
    printf("%s", prompt);
    if (fgets(buf, sizeof(buf), stdin) != NULL) {
        if (buf[0] == 'q' || buf[0] == 'Q') {
            return false; // User requested exit
        }
    }
    return true;
}

// Print an integer in binary representation
void print_binary(unsigned int num, int bits) {
    for (int i = bits - 1; i >= 0; i--) {
        printf("%d", (num >> i) & 1);
    }
}

// Check if a page is currently loaded in RAM
int find_page(int frames[], int num_frames, int page) {
    for (int i = 0; i < num_frames; i++) {
        if (frames[i] == page) return i;
    }
    return -1;
}

// Print RAM frame contents
void print_frames(int frames[], int num_frames) {
    printf("[ ");
    for (int i = 0; i < num_frames; i++) {
        if (frames[i] == -1) printf("- ");
        else printf("%d ", frames[i]);
    }
    printf("]");
}

// (a) Paginated Address Translation Table
bool display_translation_table(int virtual_addresses[], int page_ref_string[]) {
    int total_pages = (TOTAL_ADDR + ROWS_PER_PAGE - 1) / ROWS_PER_PAGE;

    for (int p = 0; p < total_pages; p++) {
        int start = p * ROWS_PER_PAGE;
        int end = start + ROWS_PER_PAGE;
        if (end > TOTAL_ADDR) end = TOTAL_ADDR;

        printf("\n=========================================================================================\n");
        printf("       (a) VIRTUAL ADDRESS TRANSLATION TABLE (Page %d of %d)\n", p + 1, total_pages);
        printf("=========================================================================================\n");
        printf("%-5s | %-12s | %-14s | %-16s | %-14s | %-10s\n",
               "Index", "V. Address", "6-bit Binary", "Page Bits (2b)", "Offset (4b)", "Page Number");
        printf("-----------------------------------------------------------------------------------------\n");

        for (int i = start; i < end; i++) {
            int v_addr = virtual_addresses[i];
            int page_num = (v_addr >> OFFSET_BITS) & 0x03;
            int offset = v_addr & 0x0F;
            page_ref_string[i] = page_num;

            printf("#%-4d | %-12d | ", i + 1, v_addr);
            print_binary(v_addr, 6);
            printf("         | ");
            print_binary(page_num, PAGE_BITS);
            printf(" (%d)          | ", page_num);
            print_binary(offset, OFFSET_BITS);
            printf(" (%-2d)    | %-10d\n", offset, page_num);
        }
        printf("=========================================================================================\n");

        if (p < total_pages - 1) {
            if (!wait_for_enter("Press [Enter] for next page (or 'q' to quit): ")) return false;
        } else {
            if (!wait_for_enter("Press [Enter] to view the Page Reference String & FIFO (or 'q' to quit): ")) return false;
        }
    }
    return true;
}

// (b) FIFO Simulation with Pagination
bool simulate_fifo(int ref_string[], int n) {
    int frames[NUM_FRAMES] = {-1, -1, -1};
    int fifo_ptr = 0;
    int page_faults = 0;
    int total_pages = (n + ROWS_PER_PAGE - 1) / ROWS_PER_PAGE;

    for (int p = 0; p < total_pages; p++) {
        int start = p * ROWS_PER_PAGE;
        int end = start + ROWS_PER_PAGE;
        if (end > n) end = n;

        printf("\n=======================================================\n");
        printf("     (b) FIFO PAGE REPLACEMENT (Page %d of %d)\n", p + 1, total_pages);
        printf("=======================================================\n");
        printf("%-5s | %-6s | %-15s | %-12s\n", "Step", "Page", "RAM Frames", "Status");
        printf("-------------------------------------------------------\n");

        for (int i = start; i < end; i++) {
            int page = ref_string[i];
            int hit_idx = find_page(frames, NUM_FRAMES, page);
            bool fault = false;

            if (hit_idx == -1) {
                fault = true;
                page_faults++;
                frames[fifo_ptr] = page;
                fifo_ptr = (fifo_ptr + 1) % NUM_FRAMES;
            }

            printf("%-5d | %-6d | ", i + 1, page);
            print_frames(frames, NUM_FRAMES);
            printf("    | %s\n", fault ? "FAULT (PF)" : "HIT");
        }
        printf("-------------------------------------------------------\n");

        if (p == total_pages - 1) {
            printf("Total Page Faults under FIFO: %d\n", page_faults);
            if (!wait_for_enter("Press [Enter] to proceed to LRU Simulation (or 'q' to quit): ")) return false;
        } else {
            if (!wait_for_enter("Press [Enter] for next page of FIFO (or 'q' to quit): ")) return false;
        }
    }
    return true;
}

// (c) LRU Simulation with Pagination
bool simulate_lru(int ref_string[], int n) {
    int frames[NUM_FRAMES] = {-1, -1, -1};
    int last_used[NUM_FRAMES] = {0};
    int page_faults = 0;
    int total_pages = (n + ROWS_PER_PAGE - 1) / ROWS_PER_PAGE;

    for (int p = 0; p < total_pages; p++) {
        int start = p * ROWS_PER_PAGE;
        int end = start + ROWS_PER_PAGE;
        if (end > n) end = n;

        printf("\n=======================================================\n");
        printf("      (c) LRU PAGE REPLACEMENT (Page %d of %d)\n", p + 1, total_pages);
        printf("=======================================================\n");
        printf("%-5s | %-6s | %-15s | %-12s\n", "Step", "Page", "RAM Frames", "Status");
        printf("-------------------------------------------------------\n");

        for (int i = start; i < end; i++) {
            int page = ref_string[i];
            int hit_idx = find_page(frames, NUM_FRAMES, page);
            bool fault = false;

            if (hit_idx != -1) {
                last_used[hit_idx] = i;
            } else {
                fault = true;
                page_faults++;

                int replace_idx = -1;
                for (int f = 0; f < NUM_FRAMES; f++) {
                    if (frames[f] == -1) {
                        replace_idx = f;
                        break;
                    }
                }

                if (replace_idx == -1) {
                    int min_time = last_used[0];
                    replace_idx = 0;
                    for (int f = 1; f < NUM_FRAMES; f++) {
                        if (last_used[f] < min_time) {
                            min_time = last_used[f];
                            replace_idx = f;
                        }
                    }
                }

                frames[replace_idx] = page;
                last_used[replace_idx] = i;
            }

            printf("%-5d | %-6d | ", i + 1, page);
            print_frames(frames, NUM_FRAMES);
            printf("    | %s\n", fault ? "FAULT (PF)" : "HIT");
        }
        printf("-------------------------------------------------------\n");

        if (p == total_pages - 1) {
            printf("Total Page Faults under LRU: %d\n", page_faults);
            if (!wait_for_enter("Press [Enter] to proceed to Optimal Simulation (or 'q' to quit): ")) return false;
        } else {
            if (!wait_for_enter("Press [Enter] for next page of LRU (or 'q' to quit): ")) return false;
        }
    }
    return true;
}

// (d) Optimal Simulation with Pagination
bool simulate_optimal(int ref_string[], int n) {
    int frames[NUM_FRAMES] = {-1, -1, -1};
    int page_faults = 0;
    int total_pages = (n + ROWS_PER_PAGE - 1) / ROWS_PER_PAGE;

    for (int p = 0; p < total_pages; p++) {
        int start = p * ROWS_PER_PAGE;
        int end = start + ROWS_PER_PAGE;
        if (end > n) end = n;

        printf("\n=======================================================\n");
        printf("    (d) OPTIMAL (OPT) REPLACEMENT (Page %d of %d)\n", p + 1, total_pages);
        printf("=======================================================\n");
        printf("%-5s | %-6s | %-15s | %-12s\n", "Step", "Page", "RAM Frames", "Status");
        printf("-------------------------------------------------------\n");

        for (int i = start; i < end; i++) {
            int page = ref_string[i];
            int hit_idx = find_page(frames, NUM_FRAMES, page);
            bool fault = false;

            if (hit_idx == -1) {
                fault = true;
                page_faults++;

                int replace_idx = -1;
                // Empty frame check
                for (int f = 0; f < NUM_FRAMES; f++) {
                    if (frames[f] == -1) {
                        replace_idx = f;
                        break;
                    }
                }

                // Lookahead to find victim
                if (replace_idx == -1) {
                    int farthest = -1;
                    for (int f = 0; f < NUM_FRAMES; f++) {
                        int next_use = -1;
                        for (int j = i + 1; j < n; j++) {
                            if (ref_string[j] == frames[f]) {
                                next_use = j;
                                break;
                            }
                        }

                        if (next_use == -1) {
                            replace_idx = f;
                            break;
                        }

                        if (next_use > farthest) {
                            farthest = next_use;
                            replace_idx = f;
                        }
                    }
                }

                frames[replace_idx] = page;
            }

            printf("%-5d | %-6d | ", i + 1, page);
            print_frames(frames, NUM_FRAMES);
            printf("    | %s\n", fault ? "FAULT (PF)" : "HIT");
        }
        printf("-------------------------------------------------------\n");

        if (p == total_pages - 1) {
            printf("Total Page Faults under OPT: %d (Minimum possible)\n", page_faults);
            wait_for_enter("\nAll simulations complete. Press [Enter] to exit program: ");
        } else {
            if (!wait_for_enter("Press [Enter] for next page of OPT (or 'q' to quit): ")) return false;
        }
    }
    return true;
}

int main() {
    int virtual_addresses[TOTAL_ADDR] = {
        0, 1, 20, 2, 20, 21, 32, 31, 0, 60,
        0, 0, 16, 1, 17, 18, 32, 31, 0, 61
    };
    int page_ref_string[TOTAL_ADDR];

    // Run each step sequentially with [Enter] pagination
    if (!display_translation_table(virtual_addresses, page_ref_string)) return 0;

    printf("\nExtracted Reference String (%d pages):\n", TOTAL_ADDR);
    for (int i = 0; i < TOTAL_ADDR; i++) {
        printf("%d ", page_ref_string[i]);
    }
    printf("\n");

    if (!simulate_fifo(page_ref_string, TOTAL_ADDR)) return 0;
    if (!simulate_lru(page_ref_string, TOTAL_ADDR)) return 0;
    if (!simulate_optimal(page_ref_string, TOTAL_ADDR)) return 0;

    return 0;
}